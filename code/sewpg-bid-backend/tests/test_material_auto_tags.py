        (f"{EW67}/部件", "动力电缆（常规方案）.pdf", ["EW6.7-202", "部件", "动力电缆"]),
        (f"{EW67}/部件", "驱动链（齿轮箱采用二级行星+一级平行轴）.docx", ["EW6.7-202", "部件", "驱动链"]),
        (f"{EW67}/部件", "叶片（玻璃纤维增强树脂基复合材料GFRP）.pdf", ["EW6.7-202", "部件", "叶片"]),
        # 半角括号同样剥掉
        (f"{EW67}/部件", "发电系统(常规方案).pdf", ["EW6.7-202", "部件", "发电系统"]),
        # 认证证书：有五级用五级（示例 row17-row22）
        (f"{EW67}/认证证书/部件认证/变流器", "EW6.7-202-CGC2025461310034上海电气.pdf", ["EW6.7-202", "认证证书", "变流器"]),
        (f"{EW67}/认证证书/部件认证/叶片", "EW6.7-202-CQC24030446050-(天顺常熟)S98V2A叶片型式认证A-20241016.pdf", ["EW6.7-202", "认证证书", "叶片"]),
        # 认证证书：有四级无五级 → 四级原文（部件认证无映射）
        (f"{EW67}/认证证书/部件认证", "xxx.pdf", ["EW6.7-202", "认证证书", "部件认证"]),
        # 认证证书：直接挂类别下 → 无标签3（示例 row23-row33）
        (f"{EW67}/认证证书", "EW6.7-202-CGC-B-FNc-2024-296 A0上海电气噪声测试报告.pdf", ["EW6.7-202", "认证证书"]),
        # 机型标签以目录为准而不是文件名（示例 row33：EW6.7-220 文件放 EW6.7-202 目录）
        (f"{EW67}/认证证书", "EW6.7-220-125-CQC25030413947113上海电气型式认证B-20251107.pdf", ["EW6.7-202", "认证证书"]),
        # 专题：四级映射（示例 row40-row77）
        (f"{EW67}/专题/设备安装与调试方案", "调试解决方案.pdf", ["EW6.7-202", "专题", "设备安装与调试"]),
