        (f"{EW67}/机型参数表", "EW6.7-202机型参数表.xlsx", ["EW6.7-202", "机型参数表"]),
        # 文件直接挂机型目录 → 只有机型标签
        (EW67, "总体介绍.pdf", ["EW6.7-202"]),
        # 文件不在机型目录下 → 不打标签
        ("技术标/标准文件", "通用说明.pdf", []),
        ("技术标", "通用说明.pdf", []),
        # 机型号小数点保护：目录名不被截断
